import { PrismaClient } from '@prisma/client';

const prisma = new PrismaClient();

async function main() {
  try {
    // Do not set id — PostgreSQL gen_random_uuid() assigns it
    let tenantA = await prisma.tenant.findFirst({ where: { name: 'Tenant A' } });
    if (!tenantA) {
      tenantA = await prisma.tenant.create({ data: { name: 'Tenant A' } });
    }

    let tenantB = await prisma.tenant.findFirst({ where: { name: 'Tenant B' } });
    if (!tenantB) {
      tenantB = await prisma.tenant.create({ data: { name: 'Tenant B' } });
    }

    console.log('Seeded tenants (UUIDs generated by PostgreSQL):');
    console.log(`  Tenant A: ${tenantA.id}`);
    console.log(`  Tenant B: ${tenantB.id}`);
  } catch (error) {
    console.error('Seed failed:', error);
    throw error;
  }
}

main()
  .then(async () => {
    await prisma.$disconnect();
  })
  .catch(async (error) => {
    console.error(error);
    await prisma.$disconnect();
    process.exit(1);
  });
