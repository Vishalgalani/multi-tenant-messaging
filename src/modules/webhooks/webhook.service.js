import { Prisma } from '@prisma/client';
import { prisma } from '../../config/database.js';
import {
  evaluateStatusTransition,
  statusTimestampFields,
} from '../../constants/messageStatus.js';
import { ApiError } from '../../utils/ApiError.js';
import { logger } from '../../utils/logger.js';
import { messageRepository } from '../messages/message.repository.js';
import { webhookRepository } from './webhook.repository.js';

function toEventResponse(event, extras = {}) {
  return {
    id: event.id,
    eventId: event.eventId,
    messageId: event.messageId,
    status: event.status,
    occurredAt: event.occurredAt,
    applied: event.applied,
    reason: event.reason,
    duplicate: Boolean(extras.duplicate),
    messageStatus: extras.messageStatus ?? null,
  };
}

function rethrowServiceError(error, fallbackMessage) {
  if (error instanceof ApiError) {
    throw error;
  }

  logger.error({ err: error }, fallbackMessage);
  throw ApiError.internal(fallbackMessage, error);
}

export const webhookService = {
  /**
   * Persist the webhook event before acknowledging success.
   * Uses a transaction + row lock so concurrent status updates are serialized.
   * Duplicate eventId returns the original processing outcome without re-applying effects.
   */
  async handleProviderEvent(payload) {
    try {
      const occurredAt = new Date(payload.occurredAt);

      if (Number.isNaN(occurredAt.getTime())) {
        throw ApiError.validation('Invalid occurredAt', [
          {
            field: 'occurredAt',
            message: 'Must be a valid ISO-8601 timestamp',
            location: 'body',
          },
        ]);
      }

      const existingMessage = await messageRepository.findById(payload.messageId);
      if (!existingMessage) {
        throw ApiError.notFound('Message not found for webhook event');
      }

      try {
        const result = await prisma.$transaction(async (tx) => {
          const existingEvent = await webhookRepository.findByEventId(payload.eventId, tx);
          if (existingEvent) {
            const message = await messageRepository.findById(existingEvent.messageId, tx);
            return {
              event: existingEvent,
              duplicate: true,
              messageStatus: message?.status ?? null,
            };
          }

          const lockedMessage = await webhookRepository.lockMessage(payload.messageId, tx);
          if (!lockedMessage) {
            throw ApiError.notFound('Message not found for webhook event');
          }

          const transition = evaluateStatusTransition(lockedMessage.status, payload.status);
          let messageStatus = lockedMessage.status;

          if (transition.allowed) {
            const updated = await webhookRepository.updateMessageStatus(
              payload.messageId,
              statusTimestampFields(payload.status, occurredAt),
              tx,
            );
            messageStatus = updated.status;
          }

          // webhook_events.id is generated by PostgreSQL (gen_random_uuid())
          const event = await webhookRepository.createEvent(
            {
              eventId: payload.eventId,
              messageId: payload.messageId,
              status: payload.status,
              occurredAt,
              applied: transition.allowed,
              reason: transition.reason,
            },
            tx,
          );

          return {
            event,
            duplicate: false,
            messageStatus,
          };
        });

        logger.info(
          {
            eventId: result.event.eventId,
            messageId: result.event.messageId,
            status: result.event.status,
            applied: result.event.applied,
            duplicate: result.duplicate,
          },
          'Webhook event processed',
        );

        return toEventResponse(result.event, {
          duplicate: result.duplicate,
          messageStatus: result.messageStatus,
        });
      } catch (error) {
        if (error instanceof Prisma.PrismaClientKnownRequestError && error.code === 'P2002') {
          try {
            const existingEvent = await webhookRepository.findByEventId(payload.eventId);
            if (existingEvent) {
              const message = await messageRepository.findById(existingEvent.messageId);
              logger.info({ eventId: payload.eventId }, 'Duplicate webhook event acknowledged');
              return toEventResponse(existingEvent, {
                duplicate: true,
                messageStatus: message?.status ?? null,
              });
            }
          } catch (lookupError) {
            rethrowServiceError(lookupError, 'Failed to resolve duplicate webhook event');
          }
        }

        if (error instanceof ApiError) {
          throw error;
        }

        throw error;
      }
    } catch (error) {
      rethrowServiceError(error, 'Failed to process provider webhook');
    }
  },
};
