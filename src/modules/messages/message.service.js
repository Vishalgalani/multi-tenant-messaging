import { prisma } from '../../config/database.js';
import { ApiError } from '../../utils/ApiError.js';
import { decodeCursor, encodeCursor } from '../../utils/ids.js';
import { logger } from '../../utils/logger.js';
import { MESSAGE_STATUS } from '../../constants/messageStatus.js';
import { messageRepository } from './message.repository.js';

function toPublicMessage(message) {
  return {
    id: message.id,
    tenantId: message.tenantId,
    conversationId: message.conversationId,
    to: message.to,
    text: message.text,
    status: message.status,
    statusUpdatedAt: message.statusUpdatedAt,
    sentAt: message.sentAt,
    deliveredAt: message.deliveredAt,
    readAt: message.readAt,
    failedAt: message.failedAt,
    createdAt: message.createdAt,
    updatedAt: message.updatedAt,
  };
}

function rethrowServiceError(error, fallbackMessage) {
  if (error instanceof ApiError) {
    throw error;
  }

  logger.error({ err: error }, fallbackMessage);
  throw ApiError.internal(fallbackMessage, error);
}

export const messageService = {
  async createMessage({ authenticatedTenantId, payload }) {
    try {
      if (payload.tenantId !== authenticatedTenantId) {
        throw ApiError.forbidden('tenantId in body must match x-tenant-id header');
      }

      // message.id is generated by PostgreSQL (gen_random_uuid()), not by the app.
      // tenantId must already exist (also DB-generated via POST /api/v1/tenants).
      const message = await prisma.$transaction(async (tx) => {
        const tenant = await messageRepository.findTenantById(payload.tenantId, tx);
        if (!tenant) {
          throw ApiError.notFound('Tenant not found');
        }

        return messageRepository.createMessage(
          {
            tenantId: payload.tenantId,
            conversationId: payload.conversationId,
            to: payload.to,
            text: payload.text,
            status: MESSAGE_STATUS.QUEUED,
          },
          tx,
        );
      });

      logger.info(
        {
          messageId: message.id,
          tenantId: message.tenantId,
          conversationId: message.conversationId,
          status: message.status,
        },
        'Message created',
      );

      return toPublicMessage(message);
    } catch (error) {
      rethrowServiceError(error, 'Failed to create message');
    }
  },

  async getMessage({ authenticatedTenantId, messageId }) {
    try {
      const message = await messageRepository.findByIdForTenant(messageId, authenticatedTenantId);

      if (!message) {
        throw ApiError.notFound('Message not found');
      }

      return toPublicMessage(message);
    } catch (error) {
      rethrowServiceError(error, 'Failed to retrieve message');
    }
  },

  async listConversationMessages({ authenticatedTenantId, conversationId, limit, cursor }) {
    try {
      let decodedCursor = null;

      if (cursor) {
        decodedCursor = decodeCursor(cursor);
        if (!decodedCursor || Number.isNaN(decodedCursor.createdAt.getTime())) {
          throw ApiError.validation('Invalid cursor', [
            { field: 'cursor', message: 'Cursor is malformed', location: 'query' },
          ]);
        }
      }

      const rows = await messageRepository.listByConversation({
        tenantId: authenticatedTenantId,
        conversationId,
        limit,
        cursor: decodedCursor,
      });

      const hasMore = rows.length > limit;
      const items = hasMore ? rows.slice(0, limit) : rows;
      const last = items[items.length - 1];

      return {
        items: items.map(toPublicMessage),
        meta: {
          limit,
          hasMore,
          nextCursor:
            hasMore && last
              ? encodeCursor({
                  createdAt: last.createdAt.toISOString(),
                  id: last.id,
                })
              : null,
        },
      };
    } catch (error) {
      rethrowServiceError(error, 'Failed to list conversation messages');
    }
  },
};
